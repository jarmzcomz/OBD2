package com.autodiag.data

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Valida la VM SA2 contra los vectores oficiales de jpbede/sa2go. Si el port
 * tiene un bug de bits, este test falla en CI antes de empaquetar el APK.
 */
class Sa2SeedKeyTest {

    private fun run(opcode: IntArray, seed: Long): Long = Sa2SeedKey(opcode).execute(seed)

    @Test
    fun vector1() {
        val bc = intArrayOf(0x68, 0x03, 0x81, 0x93, 0x54, 0x41, 0x4A, 0x49, 0x4A, 0x05, 0x87, 0x53, 0x41, 0x4A, 0x49, 0x49, 0x4C)
        assertEquals(0xE376C3C5L, run(bc, 0x06060607L))
    }

    @Test
    fun vector2() {
        val bc = intArrayOf(0x68, 0x02, 0x81, 0x4A, 0x10, 0x68, 0x04, 0x93, 0x08, 0x08, 0x20, 0x09, 0x4A, 0x05, 0x87, 0x22, 0x12, 0x19, 0x54, 0x82, 0x49, 0x93, 0x07, 0x12, 0x20, 0x11, 0x82, 0x4A, 0x05, 0x87, 0x03, 0x11, 0x20, 0x10, 0x82, 0x4A, 0x01, 0x81, 0x49, 0x4C)
        assertEquals(0x3C7876D8L, run(bc, 0xA04EB1EDL))
    }

    @Test
    fun vector3() {
        val bc = intArrayOf(0x68, 0x05, 0x81, 0x4A, 0x05, 0x87, 0x5F, 0xBD, 0x5D, 0xBD, 0x49, 0x4C)
        assertEquals(0xC1393A1CL, run(bc, 0x0CF4233DL))
    }

    @Test
    fun byteSeedMatchesIntSeed() {
        val bc = intArrayOf(0x68, 0x05, 0x81, 0x4A, 0x05, 0x87, 0x5F, 0xBD, 0x5D, 0xBD, 0x49, 0x4C)
        assertEquals(0xC1393A1CL, Sa2SeedKey(bc).execute(listOf(0x0C, 0xF4, 0x23, 0x3D)))
    }
}
